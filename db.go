package main

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib"
	_ "modernc.org/sqlite"
)

// OpenDB opens the configured database and initializes its schema.
func OpenDB(rawURL string) (*sql.DB, error) {
	u, err := url.Parse(rawURL)
	if err != nil {
		// url.Error includes the input URL, which can contain credentials.
		if urlErr, ok := errors.AsType[*url.Error](err); ok {
			err = urlErr.Err
		}
		return nil, fmt.Errorf("parse storage url: %w", err)
	}

	driver, dsn := "pgx", rawURL
	switch u.Scheme {
	case "sqlite":
		driver, dsn = "sqlite", sqliteDSN(u)
		if err := os.MkdirAll(filepath.Dir(sqlitePath(u)), 0o755); err != nil {
			return nil, fmt.Errorf("create storage dir: %w", err)
		}
	case "postgres", "postgresql":
	default:
		return nil, fmt.Errorf("unsupported storage scheme %q", u.Scheme)
	}

	db, err := sql.Open(driver, dsn)
	if err != nil {
		return nil, fmt.Errorf("open storage: %w", err)
	}

	// Bound startup checks and schema creation when the database is unavailable.
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		return nil, errors.Join(fmt.Errorf("ping storage: %w", err), db.Close())
	}
	if err := initSchema(ctx, db, driver); err != nil {
		return nil, errors.Join(err, db.Close())
	}
	return db, nil
}

func initSchema(ctx context.Context, db *sql.DB, driver string) error {
	id := "INTEGER PRIMARY KEY AUTOINCREMENT"
	if driver == "pgx" {
		id = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}

	// Keep timestamp text and indexes compatible with existing SQLite data.
	queries := []string{
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS counter (
			id %s,
			gym TEXT NOT NULL,
			count INTEGER,
			capacity INTEGER,
			last_update TEXT
		)`, id),
		`CREATE INDEX IF NOT EXISTS idx_counter_gym_id ON counter(gym, id)`,
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS visit (
			id %s,
			gym TEXT NOT NULL,
			timestamp TEXT,
			action TEXT
		)`, id),
		`CREATE INDEX IF NOT EXISTS idx_visit_gym_timestamp ON visit(gym, timestamp, id)`,
	}

	for _, query := range queries {
		if _, err := db.ExecContext(ctx, query); err != nil {
			return fmt.Errorf("init storage schema: %w", err)
		}
	}
	return nil
}

func sqliteDSN(u *url.URL) string {
	path := sqlitePath(u)
	if u.RawQuery == "" {
		return path
	}
	return path + "?" + u.RawQuery
}

func sqlitePath(u *url.URL) string {
	if u.Host == "" {
		return u.Path
	}
	return strings.TrimLeft(u.Host+u.Path, "/")
}
