#!/usr/bin/env bash
set -euo pipefail

usage() {
  echo "usage: $0 source.db... target.db" >&2
  echo "       MIGRATE_POSTGRES_URL=postgres://... $0 --postgres source.db" >&2
}

abs_path() {
  local path="$1"
  local dir base
  dir=$(dirname "$path")
  base=$(basename "$path")
  mkdir -p "$dir"
  dir=$(cd "$dir" && pwd -P)
  printf '%s/%s\n' "$dir" "$base"
}

sql_quote() {
  printf "%s" "$1" | sed "s/'/''/g"
}

run_sqlite() {
  sqlite3 -batch -init /dev/null "$@"
}

# Keep the PostgreSQL transfer separate from the legacy SQLite merge below.
migrate_postgres() (
  local src target tmp counter_rows visit_rows
  target=${MIGRATE_POSTGRES_URL:-}
  case "$target" in
    postgres://*|postgresql://*) ;;
    *) echo "MIGRATE_POSTGRES_URL must be a PostgreSQL URL" >&2; exit 1 ;;
  esac
  if ! command -v psql >/dev/null 2>&1; then
    echo "psql is required" >&2
    exit 1
  fi
  if [ ! -f "$1" ] || [ ! -r "$1" ]; then
    echo "source must be a readable SQLite file: $1" >&2
    exit 1
  fi
  src=$(abs_path "$1")

  # Back up read-only first so both exports use the same snapshot.
  umask 077
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  cd "$tmp"
  run_sqlite -readonly "$src" '.backup snapshot.db'
  if [ "$(run_sqlite -readonly snapshot.db 'PRAGMA integrity_check;')" != "ok" ]; then
    echo "source integrity check failed" >&2
    exit 1
  fi

  # CSV preserves NULL versus empty text, but cannot preserve blobs or NUL bytes.
  if [ "$(run_sqlite -readonly snapshot.db "
    SELECT EXISTS(SELECT 1 FROM counter WHERE
      typeof(id) != 'integer' OR typeof(gym) != 'text' OR instr(gym, char(0)) > 0 OR
      typeof(count) NOT IN ('integer', 'null') OR typeof(capacity) NOT IN ('integer', 'null') OR
      typeof(last_update) NOT IN ('text', 'null') OR instr(last_update, char(0)) > 0)
    OR EXISTS(SELECT 1 FROM visit WHERE
      typeof(id) != 'integer' OR typeof(gym) != 'text' OR instr(gym, char(0)) > 0 OR
      typeof(timestamp) NOT IN ('text', 'null') OR instr(timestamp, char(0)) > 0 OR
      typeof(action) NOT IN ('text', 'null') OR instr(action, char(0)) > 0);")" != "0" ]; then
    echo "source contains unsupported field types or NUL bytes" >&2
    exit 1
  fi
  counter_rows=$(run_sqlite -readonly snapshot.db 'SELECT COUNT(*) FROM counter;')
  visit_rows=$(run_sqlite -readonly snapshot.db 'SELECT COUNT(*) FROM visit;')
  if [ "$counter_rows" -eq 0 ] && [ "$visit_rows" -eq 0 ]; then
    echo "source contains no rows; refusing empty migration" >&2
    exit 1
  fi
  run_sqlite -readonly -csv -nullvalue '' snapshot.db \
    'SELECT id, gym, count, capacity, last_update FROM counter ORDER BY id;' > counter.csv
  run_sqlite -readonly -csv -nullvalue '' snapshot.db \
    'SELECT id, gym, timestamp, action FROM visit ORDER BY id;' > visit.csv

  # File-based COPY avoids interpreting CSV contents as psql commands.
  # A single transaction covers schema, data, verification, and sequence restarts.
  psql --dbname="$target" -X -w -q -v ON_ERROR_STOP=1 \
    -v counter_rows="$counter_rows" -v visit_rows="$visit_rows" --single-transaction -f - <<'SQL'
SET LOCAL client_encoding = 'UTF8';
CREATE TABLE IF NOT EXISTS counter (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym TEXT NOT NULL,
  count INTEGER,
  capacity INTEGER,
  last_update TEXT
);
CREATE TABLE IF NOT EXISTS visit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym TEXT NOT NULL,
  timestamp TEXT,
  action TEXT
);
CREATE INDEX IF NOT EXISTS idx_counter_gym_id ON counter(gym, id);
CREATE INDEX IF NOT EXISTS idx_visit_gym_timestamp ON visit(gym, timestamp, id);
LOCK TABLE counter, visit IN ACCESS EXCLUSIVE MODE;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM counter) OR EXISTS (SELECT 1 FROM visit) THEN
    RAISE EXCEPTION 'destination is not empty; refusing import';
  END IF;
END $$;

CREATE TEMP TABLE import_counter ON COMMIT DROP AS TABLE counter WITH NO DATA;
CREATE TEMP TABLE import_visit ON COMMIT DROP AS TABLE visit WITH NO DATA;
CREATE TEMP TABLE import_counts ON COMMIT DROP AS
  SELECT :'counter_rows'::bigint AS counters, :'visit_rows'::bigint AS visits;
\copy import_counter FROM 'counter.csv' WITH (FORMAT csv)
\copy import_visit FROM 'visit.csv' WITH (FORMAT csv)
INSERT INTO counter (id, gym, count, capacity, last_update)
  SELECT id, gym, count, capacity, last_update FROM import_counter ORDER BY id;
INSERT INTO visit (id, gym, timestamp, action)
  SELECT id, gym, timestamp, action FROM import_visit ORDER BY id;

DO $$
DECLARE
  tbl text;
  next_id bigint;
BEGIN
  IF (SELECT COUNT(*) FROM counter) != (SELECT counters FROM import_counts) OR
     (SELECT COUNT(*) FROM visit) != (SELECT visits FROM import_counts) OR
     EXISTS ((TABLE import_counter EXCEPT ALL TABLE counter) UNION ALL
             (TABLE counter EXCEPT ALL TABLE import_counter)) OR
     EXISTS ((TABLE import_visit EXCEPT ALL TABLE visit) UNION ALL
             (TABLE visit EXCEPT ALL TABLE import_visit)) THEN
    RAISE EXCEPTION 'verification failed: row counts or values differ';
  END IF;

  -- RESTART is transactional, unlike setval. Overflow also aborts the import.
  FOREACH tbl IN ARRAY ARRAY['counter', 'visit'] LOOP
    EXECUTE format('SELECT GREATEST(COALESCE(MAX(id), 0), 0) + 1 FROM %I', tbl) INTO next_id;
    EXECUTE format('ALTER TABLE %I ALTER COLUMN id RESTART WITH %s', tbl, next_id);
  END LOOP;
END $$;
SQL
  echo "Migration committed; all rows verified. counters=$counter_rows visits=$visit_rows"
)

if ! command -v sqlite3 >/dev/null 2>&1; then
  echo "sqlite3 is required" >&2
  exit 1
fi

if [ "${1:-}" = "--postgres" ]; then
  if [ "$#" -ne 2 ]; then
    usage
    exit 1
  fi
  migrate_postgres "$2"
  exit
fi

if [ "$#" -lt 2 ]; then
  usage
  exit 1
fi

target="${!#}"
sources=("${@:1:$#-1}")

target_abs=$(abs_path "$target")

for src in "${sources[@]}"; do
  if [ ! -r "$src" ]; then
    echo "source is not readable: $src" >&2
    exit 1
  fi

  src_abs=$(abs_path "$src")
  if [ "$src_abs" = "$target_abs" ]; then
    echo "target must not be a source: $target" >&2
    exit 1
  fi

  run_sqlite "$src" "PRAGMA schema_version;" >/dev/null
done

mkdir -p "$(dirname "$target")"
rm -f "$target"

run_sqlite "$target" <<'SQL'
CREATE TABLE counter (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  gym TEXT NOT NULL,
  count INTEGER,
  capacity INTEGER,
  last_update TEXT
);

CREATE TABLE visit (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  gym TEXT NOT NULL,
  timestamp TEXT,
  action TEXT
);

CREATE INDEX idx_counter_gym_id ON counter(gym, id);
CREATE INDEX idx_visit_gym_timestamp ON visit(gym, timestamp, id);
SQL

for src in "${sources[@]}"; do
  name=$(basename "$src")
  gym=${name%.*}
  gym=$(printf "%s" "$gym" | tr '[:lower:]' '[:upper:]')

  has_count=$(run_sqlite "$src" "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = 'count';")
  has_gym=$(run_sqlite "$src" "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = 'gym';")

  src_sql=$(sql_quote "$src")
  gym_sql=$(sql_quote "$gym")

  if [ "$has_count" = "1" ]; then
    run_sqlite "$target" <<SQL
ATTACH '$src_sql' AS src;
INSERT INTO counter (gym, count, capacity, last_update)
SELECT '$gym_sql', "count", capacity, last_update FROM src."count" ORDER BY id;
DETACH src;
SQL
  fi

  if [ "$has_gym" = "1" ]; then
    run_sqlite "$target" <<SQL
ATTACH '$src_sql' AS src;
INSERT INTO visit (gym, timestamp, action)
SELECT '$gym_sql', timestamp, action FROM src.gym ORDER BY id;
DETACH src;
SQL
  fi
done
